-- =============================================================================
-- V9 — Bitácora (#42, HU-12, RF-21): entidad RegistroAuditoria de la Fig. 7. Cada acción crítica
-- deja una fila con quién, cuándo y el valor anterior y nuevo. Solo admite inserciones: un trigger
-- rechaza UPDATE, DELETE y TRUNCATE, así no alcanza con saltearse la aplicación para alterarla.
--
-- Excepción a BaseEntity: sin creado_en, modificado_en ni version. La fila no se modifica nunca, así
-- que la versión (bloqueo optimista) y la fecha de modificación no significan nada, y creado_en
-- repetiría fecha_hora.
--
-- Sin FK: es un registro histórico. El nombre del usuario queda como foto del momento y la fila
-- no impide desactivar ni depurar lo que referencia.
-- =============================================================================
CREATE TABLE registro_auditoria (
                       id_registro_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       entidad               VARCHAR(30)   NOT NULL,
                       id_entidad            BIGINT        NOT NULL,
                       accion                VARCHAR(40)   NOT NULL,
                       id_usuario            BIGINT        NOT NULL,          -- quién hizo la acción
                       nombre_usuario        VARCHAR(150)  NOT NULL,          -- su nombre en ese momento
                       fecha_hora            TIMESTAMPTZ   NOT NULL,
                       valor_anterior        JSONB,                           -- null cuando no aplica
                       valor_nuevo           JSONB,
                       CONSTRAINT ck_registro_auditoria_entidad
                           CHECK (entidad IN ('INCIDENTE', 'ORDEN_TRABAJO', 'USUARIO', 'CUADRILLA')),
                       CONSTRAINT ck_registro_auditoria_accion
                           CHECK (accion IN ('REGISTRO', 'CIERRE_SIN_OT', 'GENERACION', 'CAMBIO_ESTADO',
                                             'ASIGNACION', 'REASIGNACION', 'PAUSA', 'REANUDACION',
                                             'ANULACION', 'ALTA', 'MODIFICACION',
                                             'RESTABLECIMIENTO_CONTRASENA', 'DESACTIVACION',
                                             'ACTIVACION'))
);

CREATE INDEX ix_registro_auditoria_entidad ON registro_auditoria (entidad, id_entidad);
CREATE INDEX ix_registro_auditoria_fecha_hora ON registro_auditoria (fecha_hora DESC);

CREATE FUNCTION rechazar_cambio_registro_auditoria() RETURNS TRIGGER
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'La bitácora es inalterable: no admite %', TG_OP;
END;
$$;

CREATE TRIGGER tg_registro_auditoria_inalterable
    BEFORE UPDATE OR DELETE ON registro_auditoria
    FOR EACH ROW EXECUTE FUNCTION rechazar_cambio_registro_auditoria();

CREATE TRIGGER tg_registro_auditoria_sin_truncate
    BEFORE TRUNCATE ON registro_auditoria
    FOR EACH STATEMENT EXECUTE FUNCTION rechazar_cambio_registro_auditoria();
