-- =============================================================================
-- V8 — Adjuntos (#71): fotos del incidente. Entidad Adjunto de la Fig. 7. Hoy solo de incidentes;
-- las fotos del cierre de la OT (CU-3) van a sumar id_orden_trabajo.
-- El archivo vive en AlmacenArchivos: acá va su ubicación (una clave), nunca el contenido.
-- =============================================================================
CREATE TABLE adjunto (
                       id_adjunto          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       id_incidente        BIGINT        NOT NULL REFERENCES incidente (id_incidente),
                       nombre_original     VARCHAR(255)  NOT NULL,
                       tipo                VARCHAR(10)   NOT NULL,          -- reconocido por el contenido (TipoImagen)
                       tamanio_bytes       BIGINT        NOT NULL,
                       ubicacion           VARCHAR(255)  NOT NULL,
                       id_usuario          BIGINT        NOT NULL REFERENCES usuario (id_usuario),  -- quién la subió
                       creado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       modificado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       version             INTEGER       NOT NULL DEFAULT 0,
                       CONSTRAINT uq_adjunto_ubicacion UNIQUE (ubicacion),
                       CONSTRAINT ck_adjunto_tipo CHECK (tipo IN ('JPEG', 'PNG', 'WEBP')),
                       CONSTRAINT ck_adjunto_tamanio CHECK (tamanio_bytes > 0)
);

CREATE INDEX ix_adjunto_incidente ON adjunto (id_incidente);
