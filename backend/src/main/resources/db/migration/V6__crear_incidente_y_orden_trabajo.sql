-- -----------------------------------------------------------------------------
-- Números visibles (INC-nnnn, OT-nnnn): cuatro dígitos con ceros a la izquierda;
-- a partir de 10000 se muestran todos los dígitos, sin recortar.
-- -----------------------------------------------------------------------------
CREATE FUNCTION formatear_numero(prefijo TEXT, n BIGINT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE
    AS $$ SELECT prefijo || CASE WHEN n < 10000 THEN lpad(n::TEXT, 4, '0') ELSE n::TEXT END $$;

CREATE SEQUENCE seq_incidente_numero;
CREATE SEQUENCE seq_orden_trabajo_numero;

-- -----------------------------------------------------------------------------
-- Incidente (CU-1)
-- -----------------------------------------------------------------------------
CREATE TABLE incidente (
    id_incidente        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero              VARCHAR(20)   NOT NULL
                        DEFAULT formatear_numero('INC-', nextval('seq_incidente_numero')),
    id_instalacion      BIGINT        NOT NULL REFERENCES instalacion (id_instalacion),
    origen              VARCHAR(20)   NOT NULL,
    id_categoria_falla  BIGINT        NOT NULL REFERENCES categoria_falla (id_categoria_falla),
    prioridad           VARCHAR(20)   NOT NULL,
    descripcion         VARCHAR(2000) NOT NULL,
    estado              VARCHAR(20)   NOT NULL,
    tercero             VARCHAR(150),                         -- falla de tercero (CU-1 4b)
    causa               VARCHAR(500),
    id_usuario          BIGINT        NOT NULL REFERENCES usuario (id_usuario),  -- quién lo registró
    creado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT uq_incidente_numero UNIQUE (numero),
    CONSTRAINT ck_incidente_origen
        CHECK (origen IN ('RECLAMO_ORGANISMO', 'MONITOREO')),
    CONSTRAINT ck_incidente_prioridad
        CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT ck_incidente_estado
        CHECK (estado IN ('ABIERTO', 'EN_ESPERA_TERCERO', 'CON_OT', 'CERRADO_SIN_OT')),
    CONSTRAINT ck_incidente_tercero
        CHECK (estado <> 'EN_ESPERA_TERCERO' OR tercero IS NOT NULL)
);

CREATE INDEX ix_incidente_estado      ON incidente (estado);
CREATE INDEX ix_incidente_instalacion ON incidente (id_instalacion);

-- -----------------------------------------------------------------------------
-- Orden de trabajo (Fig. 18). El vencimiento del SLA es una condición derivada.
-- -----------------------------------------------------------------------------
CREATE TABLE orden_trabajo (
    id_orden_trabajo      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                VARCHAR(20)  NOT NULL
                          DEFAULT formatear_numero('OT-', nextval('seq_orden_trabajo_numero')),
    tipo                  VARCHAR(20)  NOT NULL,
    estado                VARCHAR(20)  NOT NULL,
    id_incidente          BIGINT       REFERENCES incidente (id_incidente),   -- las preventivas no tienen
    id_instalacion        BIGINT       NOT NULL REFERENCES instalacion (id_instalacion),
    id_cuadrilla          BIGINT       REFERENCES cuadrilla (id_cuadrilla),
    fecha_ejecucion       DATE,
    inicio_sla            TIMESTAMPTZ,
    fecha_limite          TIMESTAMPTZ,                                        -- NULL = «SLA sin definir»
    estado_anterior_pausa VARCHAR(20),                                        -- al reanudar vuelve a este
    motivo_anulacion      VARCHAR(500),
    creado_en             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uq_orden_trabajo_numero UNIQUE (numero),
    CONSTRAINT ck_orden_trabajo_tipo
        CHECK (tipo IN ('CORRECTIVA', 'PREVENTIVA')),
    CONSTRAINT ck_orden_trabajo_estado
        CHECK (estado IN ('PENDIENTE', 'ASIGNADA', 'EN_PROCESO', 'EN_PAUSA',
                          'CERRADA_TECNICA', 'VALIDADA', 'ANULADA')),
    CONSTRAINT ck_orden_trabajo_estado_anterior_pausa
        CHECK (estado_anterior_pausa IN ('PENDIENTE', 'ASIGNADA', 'EN_PROCESO')),
    CONSTRAINT ck_orden_trabajo_pausa
        CHECK ((estado = 'EN_PAUSA') = (estado_anterior_pausa IS NOT NULL)),
    CONSTRAINT ck_orden_trabajo_correctiva_incidente
        CHECK ((tipo = 'CORRECTIVA') = (id_incidente IS NOT NULL)),
    CONSTRAINT ck_orden_trabajo_preventiva_sin_limite
        CHECK (tipo <> 'PREVENTIVA' OR fecha_limite IS NULL),
    CONSTRAINT ck_orden_trabajo_anulacion
        CHECK (estado <> 'ANULADA' OR motivo_anulacion IS NOT NULL),
    CONSTRAINT ck_orden_trabajo_cuadrilla
        CHECK (estado NOT IN ('ASIGNADA', 'EN_PROCESO') OR id_cuadrilla IS NOT NULL)
);

CREATE INDEX ix_orden_trabajo_estado_fecha_limite ON orden_trabajo (estado, fecha_limite);
CREATE INDEX ix_orden_trabajo_cuadrilla           ON orden_trabajo (id_cuadrilla);
CREATE INDEX ix_orden_trabajo_incidente           ON orden_trabajo (id_incidente);
CREATE INDEX ix_orden_trabajo_instalacion         ON orden_trabajo (id_instalacion);

-- -----------------------------------------------------------------------------
-- Pausas de una OT. Solo la tabla: la lógica va en otro issue.
-- -----------------------------------------------------------------------------
CREATE TABLE pausa_ot (
    id_pausa_ot            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo       BIGINT       NOT NULL REFERENCES orden_trabajo (id_orden_trabajo),
    inicio                 TIMESTAMPTZ  NOT NULL,
    fin                    TIMESTAMPTZ,
    motivo                 VARCHAR(20)  NOT NULL,
    detalle                VARCHAR(500),
    id_usuario_pausa       BIGINT       NOT NULL REFERENCES usuario (id_usuario),
    id_usuario_reanudacion BIGINT       REFERENCES usuario (id_usuario),
    creado_en              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_en          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_pausa_ot_motivo
        CHECK (motivo IN ('TERCERO', 'MATERIALES', 'CLIMA', 'FIN_DE_JORNADA', 'OTRO')),
    CONSTRAINT ck_pausa_ot_fin
        CHECK (fin IS NULL OR fin >= inicio),
    CONSTRAINT ck_pausa_ot_reanudacion
        CHECK ((fin IS NULL) = (id_usuario_reanudacion IS NULL))
);

-- Una OT tiene a lo sumo una pausa abierta
CREATE UNIQUE INDEX uq_pausa_ot_abierta ON pausa_ot (id_orden_trabajo) WHERE fin IS NULL;

-- -----------------------------------------------------------------------------
-- Tramos de una OT por cuadrilla: asignación (HU-05) y toma/liberación (sprint 3).
-- Solo la tabla.
-- -----------------------------------------------------------------------------
CREATE TABLE tramo_cuadrilla_ot (
    id_tramo_cuadrilla_ot  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo       BIGINT       NOT NULL REFERENCES orden_trabajo (id_orden_trabajo),
    id_cuadrilla           BIGINT       NOT NULL REFERENCES cuadrilla (id_cuadrilla),
    desde                  TIMESTAMPTZ  NOT NULL,
    hasta                  TIMESTAMPTZ,
    creado_en              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    modificado_en          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_tramo_cuadrilla_ot_hasta
        CHECK (hasta IS NULL OR hasta >= desde)
);

-- Una OT está a cargo de a lo sumo una cuadrilla a la vez
CREATE UNIQUE INDEX uq_tramo_cuadrilla_ot_abierto ON tramo_cuadrilla_ot (id_orden_trabajo)
    WHERE hasta IS NULL;
CREATE INDEX ix_tramo_cuadrilla_ot_cuadrilla ON tramo_cuadrilla_ot (id_cuadrilla);
