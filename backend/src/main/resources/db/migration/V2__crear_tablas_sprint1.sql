-- =============================================================================
-- V2 — Modelo de datos del sprint 1 (issue #22)
-- Tablas de HU-01 (usuarios y cuadrillas) y HU-02 (organismos, categorías de
-- falla, reglas de SLA e instalaciones), a partir del MER (Fig. 20).
-- Convenciones: anteproyecto 1.13.1.6.1 y CLAUDE.md (snake_case, singular,
-- PK id_<entidad>, maestros con baja lógica). Las columnas creado_en,
-- modificado_en y version son las de BaseEntity (docs/guia-arquitectura.md).
-- Solo estructura: los catálogos se cargan en HU-02 y los datos de prueba en #24.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Catálogos (RF-29)
-- -----------------------------------------------------------------------------
CREATE TABLE organismo (
    id_organismo        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL UNIQUE,
    creado_en           TIMESTAMP    NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    version             INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE regla_sla (
    id_regla_sla        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organismo        BIGINT       NOT NULL REFERENCES organismo (id_organismo),
    prioridad           VARCHAR(20)  NOT NULL,
    horas_respuesta     INTEGER      NOT NULL CHECK (horas_respuesta > 0),
    horas_resolucion    INTEGER      NOT NULL CHECK (horas_resolucion > 0),
    creado_en           TIMESTAMP    NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    version             INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uq_regla_sla_organismo_prioridad UNIQUE (id_organismo, prioridad)
);

CREATE TABLE categoria_falla (
    id_categoria_falla  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL UNIQUE,
    prioridad_sugerida  VARCHAR(20)  NOT NULL,
    activa              BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en           TIMESTAMP    NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    version             INTEGER      NOT NULL DEFAULT 0
);

-- -----------------------------------------------------------------------------
-- Instalaciones: datos mínimos de la importación inicial (RF-29)
-- -----------------------------------------------------------------------------
CREATE TABLE instalacion (
    id_instalacion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(30)   NOT NULL UNIQUE,
    nombre              VARCHAR(150)  NOT NULL,
    tipo                VARCHAR(50),
    direccion           VARCHAR(200),
    ruta_zona           VARCHAR(100)  NOT NULL,
    latitud             NUMERIC(9, 6) NOT NULL CHECK (latitud  BETWEEN -90  AND 90),
    longitud            NUMERIC(9, 6) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    id_organismo        BIGINT        NOT NULL REFERENCES organismo (id_organismo),
    activa              BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en           TIMESTAMP     NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMP     NOT NULL DEFAULT now(),
    version             INTEGER       NOT NULL DEFAULT 0
);

CREATE INDEX ix_instalacion_organismo ON instalacion (id_organismo);

-- -----------------------------------------------------------------------------
-- Cuadrillas y usuarios (RF-20, RF-23, RNF-3)
-- -----------------------------------------------------------------------------
CREATE TABLE cuadrilla (
    id_cuadrilla        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL UNIQUE,
    zona                VARCHAR(100),
    creado_en           TIMESTAMP    NOT NULL DEFAULT now(),
    modificado_en       TIMESTAMP    NOT NULL DEFAULT now(),
    version             INTEGER      NOT NULL DEFAULT 0
);

-- La tabla usuario ya existe desde V1 (usuario de ejemplo, sin datos). Una
-- migración que está en develop no se edita, así que se ajusta acá al MER:
-- el acceso es por correo (CU-13a), por lo que nombre_usuario deja de usarse.
ALTER TABLE usuario DROP COLUMN nombre_usuario;
ALTER TABLE usuario RENAME COLUMN fecha_creacion TO creado_en;
ALTER TABLE usuario ALTER COLUMN creado_en TYPE TIMESTAMP;

ALTER TABLE usuario
    ADD COLUMN nombre            VARCHAR(150) NOT NULL,
    ADD COLUMN password_hash     VARCHAR(100) NOT NULL,          -- BCrypt
    ADD COLUMN rol               VARCHAR(20)  NOT NULL,
    ADD COLUMN intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    ADD COLUMN bloqueado_hasta   TIMESTAMP,                      -- bloqueo temporal (RNF-3, CU-12 4c)
    ADD COLUMN id_cuadrilla      BIGINT       REFERENCES cuadrilla (id_cuadrilla),
    ADD COLUMN modificado_en     TIMESTAMP    NOT NULL DEFAULT now(),
    ADD COLUMN version           INTEGER      NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_usuario_rol
        CHECK (rol IN ('JEFATURA', 'TECNICO', 'OPERADOR', 'ENCARGADO_STOCK')),
    ADD CONSTRAINT ck_usuario_tecnico_cuadrilla                  -- CU-13a 4b
        CHECK (rol <> 'TECNICO' OR id_cuadrilla IS NOT NULL),
    ADD CONSTRAINT ck_usuario_intentos
        CHECK (intentos_fallidos >= 0);

CREATE INDEX ix_usuario_cuadrilla ON usuario (id_cuadrilla);
